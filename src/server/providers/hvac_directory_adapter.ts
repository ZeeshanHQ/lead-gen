export class HvacDirectoryAdapter implements DiscoveryAdapter {
  metadata = HVAC_DIRECTORY_METADATA;

  isConfigured(_config: Record<string, unknown>): boolean {
    return true;
  }

  async discover(query: DiscoveryQuery, _config: Record<string, unknown>): Promise<DiscoveredCandidate[]> {
    const candidates: DiscoveredCandidate[] = [];
    const stateFilter = query.states && query.states.length > 0 
      ? new Set(query.states.map((s) => s.toUpperCase())) 
      : null;
    const cityFilter = query.cities && query.cities.length > 0 
      ? new Set(query.cities.map((c) => c.toLowerCase())) 
      : null;

    // 1. First pass: strict match on user's active geographic filter
    for (const item of demoSeedEnabled() ? DIRECTORY_SEED_DATA : []) {
      if (candidates.length >= query.limit) break;

      if (stateFilter && !stateFilter.has(item.state.toUpperCase())) continue;
      if (cityFilter && !cityFilter.has(item.city.toLowerCase())) continue;

      candidates.push({
        name: item.name,
        website: item.website,
        phone: item.phone,
        city: item.city,
        state: item.state,
        zip: item.zip,
        provider: "hvac_directory",
        providerRef: `acca_${item.state.toLowerCase()}_${item.name.toLowerCase().replace(/[^a-z0-9]/g, "_")}`,
        sourceUrl: "https://www.acca.org/contractor-locator",
        rawPayload: item,
      });
    }

    // 2. Second pass: if user requested more candidates than strictly match specific city/state,
    // or if states are empty / broad, fill up to query.limit from other US target markets
    if (candidates.length < query.limit && (!cityFilter || cityFilter.size === 0)) {
      const existingRefs = new Set(candidates.map((c) => c.providerRef));
      for (const item of demoSeedEnabled() ? DIRECTORY_SEED_DATA : []) {
        if (candidates.length >= query.limit) break;
        const ref = `acca_${item.state.toLowerCase()}_${item.name.toLowerCase().replace(/[^a-z0-9]/g, "_")}`;
        if (existingRefs.has(ref)) continue;

        // If state filter is set, honor state filter strictly
        if (stateFilter && !stateFilter.has(item.state.toUpperCase())) continue;

        candidates.push({
          name: item.name,
          website: item.website,
          phone: item.phone,
          city: item.city,
          state: item.state,
          zip: item.zip,
          provider: "hvac_directory",
          providerRef: ref,
          sourceUrl: "https://www.acca.org/contractor-locator",
          rawPayload: item,
        });
      }
    }

    return candidates;
  }
}
